#!/usr/bin/env python3
"""Prepare exact-layout CUDA benchmark inputs and independently verify GPU hits.

Only writes this mechanism directory. Does not change the trusted GPU kernel.
The real DER gate is timed separately; low-difficulty hits exercise exactly the
same sighashes, EC recovery, encodings, and chains, but are not production solves.
"""
import argparse
import hashlib
import json
import math
import random
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import build as proto
from qsbcore import enc, find_and_delete, push_min, recover, ser_tx, sighash_all
from real_spend import midstate, nonce_of, tx_parts

ROOT = HERE.parents[2]
OUT = HERE / 'gpu_validation'


def unrank(n, t, rank):
    assert 0 <= rank < math.comb(n, t)
    chosen = []
    for pos in range(n):
        if not t:
            break
        count = math.comb(n-pos-1, t-1)
        if rank < count:
            chosen.append(pos)
            t -= 1
        else:
            rank -= count
    assert t == 0 and rank == 0
    return chosen


def preimage(script, nonce=bytes(8)):
    ins, outs, idx, locktime = tx_parts(nonce)
    replaced = [(txid, vout, script if i == idx else b'', seq)
                for i, (txid, vout, _, seq) in enumerate(ins)]
    return ser_tx(replaced, outs, locktime) + struct.pack('<I', 1)


def generated_source():
    source = (ROOT / 'gpu/pool2.cu').read_text()
    begin = source.index('#ifdef ROUND_MODE')
    end = source.index('#endif', begin) + len('#endif')
    source = source[:begin] + '#ifdef ROUND_MODE\n#include "round_renderer.cuh"\n#endif' + source[end:]
    begin = source.index('#ifdef ROUND_MODE', source.index('/* ================================================================== sighash'))
    end = source.index('#else', begin)
    source = source[:begin] + '#ifndef ROUND_MODE' + source[end+len('#else'):]
    begin = source.index('#ifdef ROUND_MODE', source.index('int main('))
    end = source.index('    if (0)\n#endif', begin)
    source = source[:begin] + '#ifdef ROUND_MODE\n    load_exact(raw, nr, N);\n' + source[end:]
    source = source.replace('raw[16384]', 'raw[32768]')
    marker = '            fn(grid, block, seq, lt, extra'
    assert source.count(marker) == 1
    guard = ('#ifdef ROUND_MODE\n'
             '            if ((((uint64_t)seq << 32) | lt) + per_launch > hCombinations) {\n'
             '                fprintf(stderr, "subset space exhausted\\n"); return 2; }\n'
             '#endif\n')
    source = source.replace(marker, guard+marker)
    return '// Generated by gpu_validation.py from frozen gpu/pool2.cu; GPLv3.\n' + source


def setup():
    OUT.mkdir(exist_ok=True)
    (OUT/'pool2_exact.cu').write_text(generated_source())
    summary = []
    rng = random.Random(20261027)
    for tier in ('D', 'E'):
        artifact = json.loads((HERE/f'{tier}_candidate.json').read_text())
        cfg = artifact['cfg']
        b = proto.build(cfg)
        script = b['script']
        assert script.hex() == artifact['production_script']
        full = preimage(script)
        off = len(full)-16
        plen = ((len(full)-20)//64)*64
        suffix = full[plen:]
        assert full[off-2:off] == b'\x6a\x08' and len(suffix) <= 119
        binary = struct.pack('>8I', *midstate(full[:plen])) + struct.pack('<I', len(suffix)) + suffix
        binary += struct.pack('<III', len(full), off-plen, off-plen+4)
        (OUT/f'{tier}_pin.bin').write_bytes(binary)
        summary.append(dict(tier=tier, stage='pin', script_sha256=hashlib.sha256(script).hexdigest(),
                            midstate_bytes=plen, suffix_bytes=len(suffix), cfg=cfg))
        for rd in range(2):
            n, t = cfg['n'], cfg[f't{rd+1}']
            ordered = sorted((script.index(push_min(d)), a) for a,d in enumerate(b['dummies'][rd]))
            first = ordered[0][0]
            sc_len = len(script)-10*t
            length_template = script[:sc_len]
            template_pre = preimage(length_template)
            head_len = template_pre.index(length_template)
            head, tail = template_pre[:head_len], template_pre[head_len+sc_len:]
            raw = head + script + tail
            plen = ((len(head)+first)//64)*64
            final_len = len(raw)-10*t
            padding = b'\x80' + bytes((55-final_len)%64) + struct.pack('>Q', final_len*8)
            stream = raw[plen:] + padding
            drops = [len(head)+pos-plen for pos,_ in ordered]
            output_len = len(stream)-10*t
            assert output_len % 64 == 0
            cases = [0, 1, math.comb(n,t)-1] + [rng.randrange(math.comb(n,t)) for _ in range(100)]
            for rank in cases:
                positions = unrank(n,t,rank)
                sc = script
                model = stream
                for p in reversed(positions):
                    model = model[:drops[p]] + model[drops[p]+10:]
                    sc = find_and_delete(sc, b['dummies'][rd][ordered[p][1]])
                expected_pre = preimage(sc)
                assert raw[:plen] + model == expected_pre + padding
                ins,outs,idx,lt = tx_parts(bytes(8))
                expected_z = sighash_all(ins,outs,idx,sc,locktime=lt)
                assert int.from_bytes(hashlib.sha256(hashlib.sha256(expected_pre).digest()).digest(),'big') == expected_z
            binary = b'QSR1' + struct.pack('>8I', *midstate(raw[:plen]))
            binary += struct.pack('<5I',n,t,plen,len(stream),output_len) + stream
            binary += struct.pack(f'<{n}I',*drops)
            binary += b''.join(struct.pack('<Q',math.comb(i,j)) for i in range(151) for j in range(8))
            (OUT/f'{tier}_round{rd+1}.bin').write_bytes(binary)
            summary.append(dict(tier=tier, stage=f'round{rd+1}', n=n,t=t,
                                script_sha256=hashlib.sha256(script).hexdigest(),
                                midstate_bytes=plen, rehash_blocks=output_len//64,
                                subsets=math.comb(n,t), cpu_stream_cases=len(cases)))
    (OUT/'inputs.json').write_text(json.dumps(summary,indent=2)+'\n')
    print(json.dumps(summary,indent=2))


def verify(tier, stage, hitfile, ratefile):
    artifact = json.loads((HERE/f'{tier}_candidate.json').read_text())
    cfg = artifact['cfg']; b = proto.build(cfg)
    assert b['script'].hex() == artifact['production_script']
    rates = json.loads(Path(ratefile).read_text().strip().splitlines()[-1])
    assert rates['gate'] == 'zeros' and rates['N'] >= 24
    rows = [tuple(map(int,line.split())) for line in Path(hitfile).read_text().splitlines() if line.strip()]
    assert rows and len(rows) == len(set(rows)) == rates['hits']
    rd = None if stage == 'pin' else int(stage[-1])-1
    bound = cfg['k'] if rd is None else cfg[f'k{rd+1}']
    chain = cfg['chain_pin'] if rd is None else cfg[f'chain{rd+1}']
    assert rates['K'] == bound and rates['chain'] == chain and rates['enc'] == 3
    assert rates['hash'] == ('sha' if cfg['hash'] == 'sha256' else cfg['hash'])
    for seq,lt,j,sign,encoding,level in rows:
        assert 0 <= seq < 2**32 and 0 <= lt < 2**32
        assert 1 <= j <= bound and sign in (0,1) and encoding in (0,1,2) and 1 <= level <= chain
        if rd is not None:
            assert (seq << 32) | lt < math.comb(cfg['n'],cfg[f't{rd+1}'])
    if rd is not None:
        order = sorted(range(cfg['n']),key=lambda a:b['script'].index(push_min(b['dummies'][rd][a])))
    checked = 0; control_pass = 0
    # Uniform reproducible sample, independent of hit order or its validity.
    sample = random.Random(20261027).sample(rows,min(300,len(rows)))
    for seq,lt,j,sign,encoding,level in sample:
        sc = b['script']
        if rd is None:
            tx = tx_parts(nonce_of(seq,lt))
        else:
            positions = unrank(cfg['n'],cfg[f't{rd+1}'],(seq<<32)|lt)
            for pos in positions:
                sc = find_and_delete(sc,b['dummies'][rd][order[pos]])
            tx = tx_parts(bytes(8))
        ins,outs,idx,locktime = tx
        z = sighash_all(ins,outs,idx,sc,locktime=locktime)
        for control in (False,True):
            point = recover(1,j,z,sign if not control else 1-sign)
            h = enc(point,['comp','uncomp','hybrid'][encoding])
            for _ in range(level):
                h = hashlib.new(cfg['hash'],h).digest()
            passed = int.from_bytes(h,'big') >> (len(h)*8-rates['N']) == 0
            if control: control_pass += passed
            else: assert passed, (tier,stage,seq,lt,j,sign,encoding,level); checked += 1
    expected = rates['expected_hits']
    poisson_z = (len(rows)-expected)/math.sqrt(expected)
    assert abs(poisson_z) < 5 and control_pass == 0
    result = dict(tier=tier,stage=stage,hits=len(rows),verified=checked,failed=0,
                  control_false_pass=control_pass,poisson_z=poisson_z,
                  encodings=sorted({r[4] for r in rows}),levels=sorted({r[5] for r in rows}),
                  production_sighash=True, production_der_solve=False)
    print(json.dumps(result))
    return result


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('command',choices=['setup','verify'])
    ap.add_argument('args',nargs='*')
    args = ap.parse_args()
    if args.command == 'setup': setup()
    else: verify(*args.args)
