#!/usr/bin/env python3
"""Write QSB/Tiers.lean: the exact build inputs (parameters + randomness) of the production tier
scripts, taken from vectors/scripts.json (export_scripts.py). QSB/TierProofs.lean proves the
limits and FindAndDelete facts about these scripts; qsbcheck proves Lean's build == Python's."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
WANT = {"TS2": "ts2", "TIERA": "tierA", "TIERB": "tierB", "TIERC": "tierC", "TIERD": "tierD", "TIERE": "tierE",
        "TIER-A-SHA1": "tierASha1", "TS4": "ts4", "REAL_TS2": "realTs2"}


def lst(xs):
    return "[" + ", ".join(xs) + "]"


def hexes(ll):
    return lst(lst(f'ofHex! "{h}"' for h in l) for l in ll)


def main():
    d = json.load(open(HERE / "vectors/scripts.json"))
    out = ["-- GENERATED by gen_tiers.py from vectors/scripts.json. Do not edit.",
           "import QSB.Build", "", "namespace QSB.Tiers", "open QSB.Build", ""]
    names = []
    for e in d:
        if e["name"] not in WANT:
            continue
        p, nm = e["params"], WANT[e["name"]]
        names.append((nm, e["name"]))
        b = lambda v: "true" if v else "false"
        out.append(f"/-- {e['name']}: {len(e['script']) // 2} bytes, {e['ops']} ops (Python build). -/")
        out.append(f"def {nm}P : Params := {{ n := {p['n']}, k := {p['k']}, ts := {p['ts']}, bs := {p['bs']}, "
                   f"kbound := {p['kbound']}, chainPin := {p['chain_pin']}, chains := {p['chains']}, "
                   f"hashOp := {p['hash_op']}, poolDeep := {b(p['pool_deep'])}, forceComp := {b(p['force_comp'])}, "
                   f"signJ := {b(p['sign_j'])}, signLvl := {b(p['sign_lvl'])} }}")
        out.append(f"def {nm}R : Rand := {{ dummies := {hexes(e['dummies'])}, pre := {hexes(e['pre'])}, "
                   f"preJ := {hexes(e['pre_j'])}, preL := {hexes(e['pre_l'])} }}")
        out.append(f"def {nm} : Built := build {nm}P {nm}R")
        out.append("")
    out.append("/-- (Lean name, qsbcheck/export name) of every tier in this file. -/")
    out.append("def all : List (String × Params × Built) := " + lst(f'("{py}", {nm}P, {nm})' for nm, py in names))
    out.append("")
    out.append("end QSB.Tiers")
    (HERE / "QSB/Tiers.lean").write_text("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
